// Status yang mewajibkan perguruan tinggi dan program studi diisi.
export const statusKuliah: StatusSetelahLulus[] = ["Aktif Kuliah", "Diterima", "Daftar Ulang"];

export function isStatusKuliah(status: StatusSetelahLulus) {
  return statusKuliah.includes(status);
}

// Status yang mengisi data pekerjaan: Bekerja (jabatan & tempat kerja) atau Wirausaha (bidang & nama usaha).
export function isStatusBekerja(status: StatusSetelahLulus) {
  return status === "Bekerja" || status === "Wirausaha";
}

export function labelPekerjaan(status: StatusSetelahLulus) {
  return status === "Wirausaha"
    ? { tempat: "Nama Usaha", jabatan: "Bidang Usaha" }
    : { tempat: "Tempat Bekerja", jabatan: "Jabatan" };
}

