  linkedin: string;
  instagram: string;
  tiktok: string;
  statusSetelahLulus: StatusSetelahLulus;
  // Mengacu ke id pada data perguruan tinggi; kosong bila belum/tidak kuliah.
  perguruanTinggiId: string;
  programStudi: string;
  // Diisi bila status "Bekerja" (jabatan & tempat kerja) atau "Wirausaha" (bidang & nama usaha).
  jabatan: string;
  tempatKerja: string;
  terakhirDikonfirmasi: string;
  validasi: StatusValidasi;
